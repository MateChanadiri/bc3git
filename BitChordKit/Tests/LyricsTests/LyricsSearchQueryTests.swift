import XCTest
@testable import Lyrics

/// Turning a YouTube title into a searchable one (ported from Android's `NewLyricsSourceTest`).
final class LyricsSearchQueryTests: XCTestCase {

    func testStripsTheCreditsACatalogueDoesNotFileATrackUnder() {
        // The one that sent a whole track to the wrong source.
        for title in ["Dracula (feat. JENNIE)", "Dracula (with JENNIE)", "Dracula [ft. JENNIE]", "Dracula feat. JENNIE", "Dracula featuring JENNIE"] {
            XCTAssertEqual(title.forLyricsSearch, "Dracula", title)
        }
    }

    func testStripsHowAnUploadWasLabelled() {
        for title in [
            "Blinding Lights (Official Video)", "Blinding Lights (Official Music Video)", "Blinding Lights [Lyrics]",
            "Blinding Lights (Visualizer)", "Blinding Lights (4K)",
        ] {
            XCTAssertEqual(title.forLyricsSearch, "Blinding Lights", title)
        }
    }

    func testLeavesAloneAnythingThatNamesADifferentRecording() {
        // These look like the same kind of bracket and are the opposite: taking them off
        // searches for a recording other than the one playing.
        for title in ["Dracula (JENNIE Remix)", "Everlong (Acoustic)", "Song 2 (Live)", "Bohemian Rhapsody (Remastered 2011)", "Nights (Sped Up)"] {
            XCTAssertEqual(title.forLyricsSearch, title)
        }
    }

    func testHandlesBothAtOnceAndLeavesOrdinaryTitlesUntouched() {
        XCTAssertEqual("Levitating (feat. DaBaby) [Official Video]".forLyricsSearch, "Levitating")
        XCTAssertEqual("golden hour".forLyricsSearch, "golden hour")
        // A title that is nothing but packaging keeps what it had.
        XCTAssertEqual("(Official Video)".forLyricsSearch, "(Official Video)")
        XCTAssertEqual("Get Lucky - ".forLyricsSearch, "Get Lucky")
    }

    func testDropsTheTopicSuffixFromAnAutoGeneratedChannel() {
        XCTAssertEqual("Tame Impala - Topic".artistForLyricsSearch, "Tame Impala")
        XCTAssertEqual("Tame Impala".artistForLyricsSearch, "Tame Impala")
    }
}

/// Reading back the source list and order as Android stores them in `AppSettings`.
final class LyricsSourceSettingsTests: XCTestCase {

    func testTheDefaultOrderIsTheDeclarationOrder() {
        XCTAssertEqual(LyricsSource.allCases.first, .biniLyrics)
        XCTAssertEqual(LyricsSource.allCases.last, .genius)
        XCTAssertEqual(LyricsSource.sourceOrder(stored: nil), LyricsSource.allCases)
        XCTAssertEqual(LyricsSource.enabledSources(stored: nil, seen: nil), Set(LyricsSource.allCases))
    }

    func testStoredNamesAreTheAndroidEnumNames() {
        XCTAssertEqual(LyricsSource.storageString([.lrcLib, .kuGou]), "LRCLIB,KUGOU")
        XCTAssertEqual(LyricsSource(rawValue: "YOUTUBE_TRANSCRIPT"), .youtubeTranscript)
    }

    func testASavedOrderKeepsItsChoicesAndAppendsNewSourcesInDeclarationOrder() {
        let order = LyricsSource.sourceOrder(stored: "LRCLIB,GONE_SOURCE,KUGOU")
        XCTAssertEqual(Array(order.prefix(2)), [.lrcLib, .kuGou])
        XCTAssertEqual(Array(order.dropFirst(2)), LyricsSource.allCases.filter { $0 != .lrcLib && $0 != .kuGou })
    }

    func testASourceAddedByAnUpgradeIsEnabledRatherThanLeftOut() {
        // Saved by an old build that only knew the legacy eight: the user turned KuGou off.
        let stored = LyricsSource.storageString(LyricsSource.legacySources.subtracting([.kuGou]))
        let enabled = LyricsSource.enabledSources(stored: stored, seen: nil)
        XCTAssertFalse(enabled.contains(.kuGou))
        XCTAssertTrue(enabled.contains(.biniLyrics), "never on the old list, so its absence says nothing")
        XCTAssertTrue(enabled.contains(.youtubeMusic))
    }

    func testASourceTheUserSawAndTurnedOffStaysOff() {
        let enabled = LyricsSource.enabledSources(stored: "LRCLIB", seen: LyricsSource.storageString(LyricsSource.allCases))
        XCTAssertEqual(enabled, [.lrcLib])
    }

    func testPreferencesClampTheOffsetAndResetSources() {
        var preferences = LyricsPreferences(enabledSources: [.lrcLib], sourceOrder: [.lrcLib], prioritizeSyllableSync: true, offsetMs: 9_000)
        XCTAssertEqual(preferences.offsetMs, 5_000)
        preferences.offsetMs = -7_000
        XCTAssertEqual(preferences.offsetMs, -5_000)
        let reset = preferences.resettingSources()
        XCTAssertEqual(reset.enabledSources, Set(LyricsSource.allCases))
        XCTAssertEqual(reset.sourceOrder, LyricsSource.allCases)
        XCTAssertFalse(reset.prioritizeSyllableSync)
        XCTAssertEqual(reset.offsetMs, -5_000)
        XCTAssertTrue(LyricsPreferences(syncedLyricsEnabled: false).activeSources.isEmpty)
    }

    func testEverySourceHasALabelAndADetail() {
        for source in LyricsSource.allCases {
            XCTAssertFalse(source.label.isEmpty)
            XCTAssertFalse(source.detail.isEmpty)
        }
        XCTAssertTrue(LyricsSource.biniLyrics.wordSynced)
        XCTAssertFalse(LyricsSource.lrcLib.wordSynced)
    }
}
